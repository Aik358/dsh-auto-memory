export const settingsSchema = object(settings)
export const settingsPatchSchema = { ...object({ ...settings, ...writeOnlySettings.properties }), minProperties: 1 }

export function projectConfig(config) {
  const projected = Object.fromEntries(Object.keys(settings).filter(name => config[name] !== undefined).map(name => [name, config[name]]))
  projected.deliveryPolicy ??= null
  if (projected.externalSources) {
    projected.externalSources = Object.fromEntries(Object.keys(externalSources.properties)
      .filter(name => typeof config.externalSources[name] === 'boolean').map(name => [name, config.externalSources[name]]))
  }
  return projected
}

export function configRevision(config) {
  const visible = revisionOf(projectConfig(config))
  const sensitive = Object.keys(writeOnlySettings.properties).map(key => config[key] || '')
  return createHmac('sha256', settingsKey).update(visible).update(JSON.stringify(sensitive)).digest('hex')
}
